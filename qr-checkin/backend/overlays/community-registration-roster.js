'use strict';

const {participantAliases, quickParticipants} = require('./community-registration-policy');
const {createHash} = require('node:crypto');
const object = value => value && typeof value === 'object' && !Array.isArray(value);
const local = player => player.source !== 'online' && !player.registrationId;
const populated = value => Array.isArray(value) ? value.length > 0 : object(value) ? Object.keys(value).length > 0 : !!value;

// This repair never invalidates a draw or rewrites results. Check both private
// runtime and public mirror: either may reveal an already advanced tournament.
function assertQuickRosterMutable(...states) {
  for (const state of states) {
    if (!object(state)) throw Error('corrupt-state');
    if (state.startedAt || state.drawnAt || state.completedAt || state.archivedAt || state.bracketSize || state.rosterLocked === true ||
        state.archiveStatus === 'completed' || ['live','settling','done','cancelled'].includes(state.tournamentPhase) ||
        ['matches','results','standings','teamStandings','rounds','bracket','brackets','courtAssignments'].some(key => populated(state[key])) ||
        ['championId','runnerUpId','thirdId','fourthId','gfMatchId','gfResetMatchId','bronzeMatchId','rrRounds','teamResultRevision','ladderPointsAwarded'].some(key => !!state[key])) {
      throw Error('roster-locked');
    }
  }
}

function assertPendingBracketOnly(...states) {
  for (const state of states) {
    if (!object(state)) throw Error('corrupt-state');
    // A generated bye is not a played match. Any score, log, result or live
    // dispatch evidence makes additive pre-start repair unsafe as well.
    if (state.matches !== undefined && !Array.isArray(state.matches)) throw Error('corrupt-state');
    if ((state.matches || []).some(match => !object(match) || match.startedAt || match.confirmedAt || match.confirmedBy ||
      match.scoreA || match.scoreB || populated(match.log) || populated(match.faultActions) || populated(match.hunterData) ||
      match.status && !(match.isBye ? ['pending','ready','queued','completed'] : ['pending','ready','queued']).includes(match.status) ||
      (!match.isBye && (match.completed || match.winnerId || match.loserId || match.resultMethod)))) throw Error('roster-locked');
    if (state.courtAssignments !== undefined && !object(state.courtAssignments)) throw Error('corrupt-state');
    if (Object.values(state.courtAssignments || {}).some(court => !object(court) || court.startedAt || court.lockedAt || court.lockedBy ||
      court.status && !['idle','pending','ready','queued'].includes(court.status))) throw Error('roster-locked');
    const pending = {...state};
    for (const key of ['matches','drawnAt','bracketSize','gfMatchId','gfResetMatchId','bronzeMatchId','rrRounds','courtAssignments']) delete pending[key];
    assertQuickRosterMutable(pending);
  }
}

function projectQuickRoster(state, registrations, options = {}) {
  if (!object(state) || !Array.isArray(state.players) || state.waitlistPlayers !== undefined && !Array.isArray(state.waitlistPlayers)) throw Error('corrupt-state');
  const previous = [...state.players, ...(state.waitlistPlayers || [])];
  if (previous.some(player => !object(player) || typeof player.id !== 'string' || !player.id)) throw Error('corrupt-state');
  if (new Set(previous.map(player => player.id)).size !== previous.length) throw Error('registration-state-conflict');
  const players = state.players.filter(local);
  const waitlistPlayers = (state.waitlistPlayers || []).filter(local);
  const localAliases = new Set(players.flatMap((player, index) => participantAliases(player, false, index)));
  const waitingAliases = new Set(waitlistPlayers.flatMap((player, index) => participantAliases(player, false, index)));
  if ([...waitingAliases].some(alias => localAliases.has(alias))) throw Error('registration-state-conflict');
  const managed = previous.filter(player => !local(player));
  const claimedAliases = new Set();
  const usedIds = new Set([...players, ...waitlistPlayers].map(player => player.id));
  const rows = registrations.filter(row => ['confirmed', 'waitlist'].includes(row.status))
    .slice().sort((a,b) => String(a.registrationId || a.uid).localeCompare(String(b.registrationId || b.uid)));
  for (const row of rows) {
    const registrationId = String(row.registrationId || row.uid || '');
    if (!registrationId || row.registrationKind === 'team' || row.teamId) throw Error('registration-state-conflict');
    const aliases = participantAliases(row, true);
    if (aliases.some(alias => waitingAliases.has(alias))) throw Error('registration-state-conflict');
    if (aliases.some(alias => claimedAliases.has(alias))) throw Error('registration-state-conflict');
    aliases.forEach(alias => claimedAliases.add(alias));
    // An already participating host/onsite player owns their local ID. A legacy
    // duplicate registration must not create another player or overwrite it.
    if (aliases.some(alias => localAliases.has(alias))) continue;
    const matches = managed.filter(player => participantAliases(player).some(alias => aliases.includes(alias)));
    if (matches.length > 1) throw Error('registration-state-conflict');
    const old = matches[0];
    const familyId = row.familyPlayerId || (registrationId.startsWith('family_') ? registrationId.slice(7) : '');
    const name = String(row.displayName || row.publicName || row.participantName || row.realName || old?.name || '').trim();
    if (!name) throw Error('registration-name-missing');
    // Existing clients resolve children from the public family_<childId> ID.
    // Keep that established contract without exposing any additional fields;
    // new account participants use room-scoped opaque IDs.
    const player = {...old,
      id: old?.id || (familyId ? 'family_' + String(familyId) : 'qr_' + createHash('sha256').update(JSON.stringify([
        options.roomCode || state.cloudCode || state.id || 'community',
        'account', String(registrationId)
      ])).digest('hex').slice(0,32)),
      name, source: 'online', registrationId,
      registrationUid: String(row.guardianUid || row.uid || registrationId),
      checkedIn: typeof old?.checkedIn === 'boolean' ? old.checkedIn : state.meta?.checkinRequired !== true
    };
    if (familyId) Object.assign(player, {familyPlayerId:String(familyId), participantId:String(familyId), guardianUid:String(row.guardianUid || '')});
    if (usedIds.has(player.id)) throw Error('registration-state-conflict');
    usedIds.add(player.id);
    if (row.status === 'waitlist') {
      player.waitRank = Number(row.waitRank) || 0;
      player.waitlistedAt = row.createdAt?.toMillis ? row.createdAt.toMillis() : Number(row.createdAt) || 0;
      waitlistPlayers.push(player);
    } else {
      delete player.waitRank; delete player.waitlistedAt;
      players.push(player);
    }
  }
  // Keep the current order and IDs; append newly projected registrations in a
  // deterministic order so retries and subsequent service calls are no-ops.
  const stable = (next, old) => {
    const positions = new Map(old.map((player,index) => [player.id,index]));
    return next.sort((a,b) => (positions.get(a.id) ?? Infinity) - (positions.get(b.id) ?? Infinity));
  };
  return {players:stable(players,state.players), waitlistPlayers:stable(waitlistPlayers,state.waitlistPlayers || [])};
}

function reconcileQuickRoster(state, mirror, registrations, options = {}) {
  if (options.allowPendingBracketChanges) assertPendingBracketOnly(state, mirror);
  else assertQuickRosterMutable(state, mirror);
  const projected = projectQuickRoster(state, registrations, options);
  const communityParticipantCount = quickParticipants({...state, ...projected}, registrations).count;
  const visible = projected.players.map(player => ({id:player.id, name:String(player.name || ''), checkedIn:player.checkedIn === true}));
  // Pending draws retain their exact match objects. The existing client checks
  // bracket IDs against eligible roster IDs again before start and requires an
  // explicit redraw when a registration joins or cancels after the first draw.
  const stateRevision = state.registrationRosterRevision ?? 0;
  const mirrorRevision = mirror.registrationRosterRevision ?? 0;
  if (![stateRevision,mirrorRevision].every(value => Number.isSafeInteger(value) && value >= 0 && value < Number.MAX_SAFE_INTEGER)) throw Error('registration-state-conflict');
  const changed = JSON.stringify(state.players) !== JSON.stringify(projected.players) ||
    JSON.stringify(state.waitlistPlayers || []) !== JSON.stringify(projected.waitlistPlayers) ||
    JSON.stringify(mirror.players || []) !== JSON.stringify(visible) ||
    state.communityParticipantCount !== communityParticipantCount || mirror.communityParticipantCount !== communityParticipantCount ||
    stateRevision !== mirrorRevision;
  if (!changed) return {state, mirror, changed:false, communityParticipantCount};
  const registrationRosterRevision = Math.max(stateRevision,mirrorRevision) + 1;
  return {
    state:{...state, ...projected, communityParticipantCount, registrationRosterRevision},
    mirror:{...mirror, players:visible, communityParticipantCount, registrationRosterRevision},
    changed:true, communityParticipantCount
  };
}

module.exports = {projectQuickRoster, reconcileQuickRoster, assertQuickRosterMutable, assertPendingBracketOnly};
